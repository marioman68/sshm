"""Import from and export to OpenSSH ``~/.ssh/config``."""

from __future__ import annotations

import glob
import os
import shlex
from dataclasses import dataclass, field
from pathlib import Path

from sshm.core import paths
from sshm.core.models import Server


@dataclass
class HostEntry:
    alias: str
    options: dict[str, str] = field(default_factory=dict)

    def to_server(self) -> Server:
        o = self.options
        port = o.get("port", "22")
        return Server(
            name=self.alias,
            host=o.get("hostname", self.alias),
            user=o.get("user", ""),
            port=int(port) if port.isdigit() else 22,
            key=o.get("identityfile", ""),
            jump=o.get("proxyjump", "") if o.get("proxyjump", "").lower() != "none" else "",
            tag="ssh_config",
        )


def default_path() -> Path:
    return paths.home() / ".ssh/config"


def _tokens(line: str) -> tuple[str, list[str]] | None:
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    if "=" in line.split()[0]:
        key, _, rest = line.partition("=")
    else:
        key, _, rest = line.partition(" ")
        if not rest:
            key, _, rest = line.partition("\t")
    try:
        values = shlex.split(rest.strip(), comments=True)
    except ValueError:
        values = rest.split()
    return key.strip().lower(), values


def parse(path: Path | None = None, _depth: int = 0) -> list[HostEntry]:
    path = path or default_path()
    try:
        text = path.read_text(errors="ignore")
    except OSError:
        return []
    entries: list[HostEntry] = []
    current: list[HostEntry] = []
    in_match = False
    for raw in text.splitlines():
        tok = _tokens(raw)
        if not tok:
            continue
        key, values = tok
        if key == "include" and _depth < 8:
            for pattern in values:
                pattern = os.path.expanduser(pattern)
                if not os.path.isabs(pattern):
                    pattern = str(paths.home() / ".ssh" / pattern)
                for inc in sorted(glob.glob(pattern)):
                    entries.extend(parse(Path(inc), _depth + 1))
            continue
        if key == "host":
            in_match = False
            current = [HostEntry(v) for v in values if not any(c in v for c in "*?!")]
            entries.extend(current)
            continue
        if key == "match":
            in_match, current = True, []
            continue
        if in_match or not values:
            continue
        for entry in current:
            entry.options.setdefault(key, values[0])  # first value wins, like ssh
    return entries


def import_servers(existing: list[Server], path: Path | None = None) -> list[Server]:
    """Servers from ssh_config that are not already present (by name or host:port)."""
    have_names = {s.name.lower() for s in existing}
    have_ep = {(s.host.lower(), s.port) for s in existing}
    out: list[Server] = []
    for entry in parse(path):
        srv = entry.to_server()
        if srv.name.lower() in have_names or (srv.host.lower(), srv.port) in have_ep:
            continue
        have_names.add(srv.name.lower())
        have_ep.add((srv.host.lower(), srv.port))
        out.append(srv)
    return out


def export(servers: list[Server]) -> str:
    blocks = ["# Generated by sshm — paste into ~/.ssh/config"]
    for s in servers:
        alias = "-".join(s.name.split()) or s.host
        lines = [f"Host {alias}", f"    HostName {s.host}"]
        if s.user:
            lines.append(f"    User {s.user}")
        if s.port != 22:
            lines.append(f"    Port {s.port}")
        if s.key:
            lines.append(f"    IdentityFile {s.key}")
        if s.jump:
            lines.append(f"    ProxyJump {s.jump}")
        blocks.append("\n".join(lines))
    return "\n\n".join(blocks) + "\n"
