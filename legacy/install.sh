#!/usr/bin/env bash
# sshm user-level installer — no root, no pip, works on any distro with python3 >= 3.10.
#
#   ./install.sh                 install / upgrade
#   ./install.sh --no-autostart  install without starting the tray at login
#   ./install.sh --uninstall     remove sshm (your servers and settings are kept)
set -euo pipefail

APP_ID="io.github.marioman68.sshm"
SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
PREFIX="$DATA_HOME/sshm"
LIB_DIR="$PREFIX/lib"
BIN_DIR="$HOME/.local/bin"
APPS_DIR="$DATA_HOME/applications"
ICON_DIR="$DATA_HOME/icons/hicolor/scalable/apps"
AUTOSTART="$CONFIG_HOME/autostart/sshm-tray.desktop"

bold=$'\e[1m'; dim=$'\e[2m'; green=$'\e[32m'; yellow=$'\e[33m'; red=$'\e[31m'; reset=$'\e[0m'
[ -t 1 ] || { bold=""; dim=""; green=""; yellow=""; red=""; reset=""; }
step() { printf '%s›%s %s\n' "$bold" "$reset" "$*"; }
ok()   { printf '%s✔%s %s\n' "$green" "$reset" "$*"; }
warn() { printf '%s⚠%s %s\n' "$yellow" "$reset" "$*"; }
die()  { printf '%s✖%s %s\n' "$red" "$reset" "$*" >&2; exit 1; }

stop_running() {
  pkill -f 'sshm-tray\.py' 2>/dev/null || true          # sshm 2.x
  pkill -f 'sshm-telem-daemon' 2>/dev/null || true      # sshm 2.x bash TUI listener
  pkill -f 'sshm\.gui\.app' 2>/dev/null || true         # sshm 3.x
  sleep 0.3
}

remove_legacy() {
  rm -f "$PREFIX/sshm.py" "$PREFIX/sshm-tray.py" "$PREFIX/sshm-hub.svg"
  rm -f "$APPS_DIR"/sshm-gui.desktop "$DATA_HOME/icons/hicolor/scalable/apps/sshm-hub.svg"
}

uninstall() {
  step "Removing sshm"
  stop_running
  remove_legacy
  rm -rf "$LIB_DIR"
  rm -f "$BIN_DIR/sshm" "$BIN_DIR/sshm-gui" "$BIN_DIR/sshm-tray"
  rm -f "$APPS_DIR/$APP_ID.desktop" "$ICON_DIR/sshm.svg" "$AUTOSTART"
  rmdir "$PREFIX" 2>/dev/null || true
  command -v update-desktop-database >/dev/null && update-desktop-database "$APPS_DIR" 2>/dev/null || true
  ok "sshm removed. Your servers and settings remain in $CONFIG_HOME/sshm"
}

AUTOSTART_WANTED=1
case "${1:-}" in
  --uninstall|-u) uninstall; exit 0 ;;
  --no-autostart) AUTOSTART_WANTED=0 ;;
  ""|--install) ;;
  -h|--help) sed -n '2,7p' "$0"; exit 0 ;;
  *) die "unknown option: $1 (try --help)" ;;
esac

# ------------------------------------------------------------------ checks
command -v python3 >/dev/null || die "python3 is required"
python3 - <<'PY' || die "sshm needs Python 3.10 or newer (found $(python3 -V 2>&1))"
import sys; raise SystemExit(0 if sys.version_info >= (3, 10) else 1)
PY
[ -d "$SRC_DIR/src/sshm" ] || die "run this script from the sshm source directory"
command -v ssh >/dev/null || warn "the OpenSSH client (ssh) is not installed"

# ----------------------------------------------------------------- install
step "Installing sshm $(sed -n 's/^__version__ = "\(.*\)"/\1/p' "$SRC_DIR/src/sshm/__init__.py") to $PREFIX"
stop_running
remove_legacy
mkdir -p "$LIB_DIR" "$BIN_DIR" "$APPS_DIR" "$ICON_DIR"
rm -rf "$LIB_DIR/sshm"
cp -r "$SRC_DIR/src/sshm" "$LIB_DIR/sshm"
find "$LIB_DIR" -name '__pycache__' -type d -prune -exec rm -rf {} +
python3 -m compileall -q "$LIB_DIR/sshm" >/dev/null 2>&1 || true

write_launcher() {  # name, python module args
  local name=$1; shift
  rm -f "$BIN_DIR/$name"
  cat > "$BIN_DIR/$name" <<EOF
#!/bin/sh
# generated by sshm install.sh
PYTHONPATH="$LIB_DIR\${PYTHONPATH:+:\$PYTHONPATH}" exec python3 -m $* "\$@"
EOF
  chmod 755 "$BIN_DIR/$name"
}
write_launcher sshm sshm
write_launcher sshm-gui sshm.gui.app --gui
write_launcher sshm-tray sshm.gui.app --tray

cp "$SRC_DIR/src/sshm/data/sshm.svg" "$ICON_DIR/sshm.svg"
sed "s|^Exec=sshm-gui|Exec=$BIN_DIR/sshm-gui|; s|^Exec=sshm-tray|Exec=$BIN_DIR/sshm-tray|; s|^Exec=sshm$|Exec=$BIN_DIR/sshm|" \
  "$SRC_DIR/packaging/$APP_ID.desktop" > "$APPS_DIR/$APP_ID.desktop"
command -v update-desktop-database >/dev/null && update-desktop-database "$APPS_DIR" 2>/dev/null || true
command -v gtk-update-icon-cache >/dev/null && gtk-update-icon-cache -q -t "$DATA_HOME/icons/hicolor" 2>/dev/null || true
command -v kbuildsycoca6 >/dev/null && kbuildsycoca6 --noincremental >/dev/null 2>&1 || true
ok "Installed sshm, sshm-gui and sshm-tray to $BIN_DIR"

# ------------------------------------------------------------- GUI support
HAVE_QT=0
if python3 -c 'import PyQt6.QtWidgets' 2>/dev/null; then
  HAVE_QT=1
else
  warn "PyQt6 is not installed — the terminal UI and CLI work, the desktop app needs it:"
  if   command -v dnf    >/dev/null; then echo "    sudo dnf install python3-pyqt6"
  elif command -v apt    >/dev/null; then echo "    sudo apt install python3-pyqt6"
  elif command -v pacman >/dev/null; then echo "    sudo pacman -S python-pyqt6"
  elif command -v zypper >/dev/null; then echo "    sudo zypper install python3-PyQt6"
  elif command -v rpm-ostree >/dev/null; then echo "    rpm-ostree install python3-pyqt6   (or run sshm-gui from a toolbox)"
  else echo "    install PyQt6 for python3 with your package manager"
  fi
fi
for tool in tmux sshfs; do
  command -v "$tool" >/dev/null || printf '  %soptional: install %s for %s%s\n' "$dim" "$tool" \
    "$([ "$tool" = tmux ] && echo 'persistent sessions' || echo 'real SSHFS mounts')" "$reset"
done

if [ "$HAVE_QT" = 1 ] && [ "$AUTOSTART_WANTED" = 1 ]; then
  mkdir -p "$(dirname "$AUTOSTART")"
  cat > "$AUTOSTART" <<EOF
[Desktop Entry]
Type=Application
Name=sshm tray monitor
Comment=Watch your SSH servers from the system tray
Exec=$BIN_DIR/sshm-tray
Icon=sshm
Terminal=false
X-GNOME-Autostart-enabled=true
X-GNOME-Autostart-Delay=5
X-KDE-autostart-after=panel
EOF
  ok "Tray monitor will start at login (disable in Settings or with --no-autostart)"
  if [ -n "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ]; then
    nohup "$BIN_DIR/sshm-tray" >/dev/null 2>&1 &
    ok "Tray monitor started"
  fi
elif [ "$AUTOSTART_WANTED" = 0 ]; then
  rm -f "$AUTOSTART"
fi

case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) warn "$BIN_DIR is not on your PATH — add it in your shell profile: export PATH=\"\$HOME/.local/bin:\$PATH\"" ;;
esac

if [ -f "$HOME/.ssh_servers" ] && [ ! -f "$CONFIG_HOME/sshm/servers.json" ]; then
  ok "Your existing ~/.ssh_servers will be imported automatically on first launch"
fi
echo
printf '  %ssshm%s        terminal UI          %ssshm --help%s   all CLI commands\n' "$bold" "$reset" "$bold" "$reset"
printf '  %ssshm-gui%s    desktop app          %ssshm-tray%s     tray monitor\n' "$bold" "$reset" "$bold" "$reset"
